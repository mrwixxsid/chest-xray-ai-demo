IMAGE_SIZE = 384
CLASSIFIER_THRESHOLD = 0.4144  # Selected on the validation set
DEFAULT_DETECTION_THRESHOLD = 0.30

IMAGENET_MEAN = torch.tensor([0.485, 0.456, 0.406]).view(3, 1, 1)
IMAGENET_STD = torch.tensor([0.229, 0.224, 0.225]).view(3, 1, 1)
DEVICE = torch.device("cpu")  # Streamlit Community Cloud free apps run on CPU.


def get_model_repo_id():
    """Read a public Hugging Face Model repository ID from Streamlit secrets or env."""
    try:
        value = st.secrets.get("HF_MODEL_REPO_ID", "")
        if value:
            return str(value).strip()
    except Exception:
        pass
    return os.getenv("HF_MODEL_REPO_ID", "YOUR_USERNAME/chest-xray-ai-models").strip()


MODEL_REPO_ID = get_model_repo_id()
CLASSIFIER_FILENAME = "densenet121_opacity_best.pth"
DETECTOR_FILENAME = "fasterrcnn_opacity_best.pth"


def download_checkpoint(filename: str) -> str:
    repo_id = MODEL_REPO_ID
    if not repo_id or "YOUR_USERNAME" in repo_id:
        raise RuntimeError(
            "Set HF_MODEL_REPO_ID to your public Hugging Face Model repository ID. "
            "See README.md for deployment instructions."
        )
    return hf_hub_download(
        repo_id=repo_id,
        filename=filename,
        repo_type="model",
    )


@st.cache_resource(show_spinner="Loading DenseNet121 classifier (first load may take a minute)...")
def load_classifier():
    checkpoint_path = download_checkpoint(CLASSIFIER_FILENAME)
    # This is the trusted checkpoint generated by the user's own training notebook.
    # weights_only=False is needed because the checkpoint includes a NumPy scalar.
    checkpoint = torch.load(
        checkpoint_path,
        map_location="cpu",
        weights_only=False,
    )
    model = densenet121(weights=None)
    model.classifier = nn.Linear(model.classifier.in_features, 1)
    model.load_state_dict(checkpoint["model_state_dict"])
    model.to(DEVICE)
    model.eval()
    return model


@st.cache_resource(show_spinner="Loading Faster R-CNN detector (first load may take a minute)...")
def load_detector():
    checkpoint_path = download_checkpoint(DETECTOR_FILENAME)
    checkpoint = torch.load(
        checkpoint_path,
        map_location="cpu",
        weights_only=True,
    )
    model = fasterrcnn_resnet50_fpn(
        weights=None,
        weights_backbone=None,
        min_size=IMAGE_SIZE,
        max_size=IMAGE_SIZE,
        box_score_thresh=0.01,
        box_detections_per_img=50,
    )
    in_features = model.roi_heads.box_predictor.cls_score.in_features
    model.roi_heads.box_predictor = FastRCNNPredictor(
        in_features,
        num_classes=2,
    )
    model.load_state_dict(checkpoint["model_state_dict"])
    model.to(DEVICE)
    model.eval()
    return model, checkpoint


def dicom_bytes_to_pil(raw_bytes: bytes) -> Image.Image:
    """Decode a single-frame DICOM with the training pipeline's intensity rules."""
    dcm = pydicom.dcmread(io.BytesIO(raw_bytes))
    pixels = dcm.pixel_array
    if pixels.ndim != 2:
        raise ValueError(
            f"Expected a 2D grayscale DICOM image; received shape {pixels.shape}."
        )

    if pixels.dtype == np.uint8:
        gray = pixels.copy()
    else:
        pixels = pixels.astype(np.float32)
        slope = float(getattr(dcm, "RescaleSlope", 1))
        intercept = float(getattr(dcm, "RescaleIntercept", 0))
        pixels = pixels * slope + intercept
        pixels = np.nan_to_num(pixels, nan=0.0, posinf=0.0, neginf=0.0)
        low, high = np.percentile(pixels, [0.5, 99.5])
        if high <= low:
            low = float(pixels.min())
            high = float(pixels.max())
        if high <= low:
            raise ValueError("DICOM image has no usable intensity range.")
        pixels = np.clip(pixels, low, high)
        gray = ((pixels - low) / (high - low) * 255.0).astype(np.uint8)

    photometric = getattr(dcm, "PhotometricInterpretation", "MONOCHROME2")
    if photometric == "MONOCHROME1":
        gray = 255 - gray
    elif photometric != "MONOCHROME2":
        raise ValueError(f"Unsupported photometric interpretation: {photometric}")

    return Image.fromarray(gray, mode="L")


def read_uploaded_image(uploaded_file) -> Image.Image:
    if uploaded_file is None:
        raise ValueError("Upload a chest X-ray first.")

    raw_bytes = uploaded_file.getvalue()
    extension = os.path.splitext(uploaded_file.name)[1].lower()

    if extension in {".dcm", ".dicom"}:
        return dicom_bytes_to_pil(raw_bytes)

    try:
        image = Image.open(io.BytesIO(raw_bytes))
        image = ImageOps.exif_transpose(image)
        return image.convert("RGB")
    except Exception as exc:
        raise ValueError(
            "Could not read this file as PNG, JPG, or DICOM. "
            "For compressed DICOM files, the needed decoder may not be installed."
        ) from exc


def prepare_uploaded_image(image: Image.Image):
    original = image.convert("RGB")
    gray = np.asarray(original.convert("L"), dtype=np.uint8)
    gray_384 = cv2.resize(
        gray,
        (IMAGE_SIZE, IMAGE_SIZE),
        interpolation=cv2.INTER_AREA,
    )
    rgb_384 = np.repeat(gray_384[:, :, None], 3, axis=2)
    rgb_384 = np.ascontiguousarray(rgb_384)

    # Detector expects float RGB tensor in [0, 1].
    detector_tensor = (
        torch.from_numpy(rgb_384)
        .permute(2, 0, 1)
        .float()
        .div(255.0)
    )

    # Classifier expects ImageNet-normalized RGB input.
    classifier_tensor = (detector_tensor - IMAGENET_MEAN) / IMAGENET_STD
    return original, classifier_tensor, detector_tensor


def draw_detections(original: Image.Image, detections, threshold: float):
    overlay = original.copy().convert("RGB")
    draw = ImageDraw.Draw(overlay)
    width, height = overlay.size
    sx = width / IMAGE_SIZE
    sy = height / IMAGE_SIZE

    try:
        font = ImageFont.truetype("DejaVuSans.ttf", max(12, width // 60))
    except OSError:
        font = ImageFont.load_default()

    shown = 0
    for box, score in zip(detections["boxes"], detections["scores"]):
        score = float(score)
        if score < threshold:
            continue

        x1, y1, x2, y2 = [float(v) for v in box]
        x1 = max(0, min(width - 1, x1 * sx))
        x2 = max(0, min(width - 1, x2 * sx))
        y1 = max(0, min(height - 1, y1 * sy))
        y2 = max(0, min(height - 1, y2 * sy))
        if x2 <= x1 or y2 <= y1:
            continue

        line_width = max(2, width // 350)
        draw.rectangle((x1, y1, x2, y2), outline=(255, 40, 40), width=line_width)
        text = f"Opacity score {score:.2f}"
        text_bbox = draw.textbbox((x1, y1), text, font=font)
        text_h = text_bbox[3] - text_bbox[1]
        label_top = max(0, y1 - text_h - 4)
        label_right = min(width - 1, text_bbox[2] + 4)
        draw.rectangle(
            (x1, label_top, label_right, label_top + text_h + 4),
            fill=(255, 40, 40),
        )
        draw.text((x1 + 2, label_top + 2), text, fill=(255, 255, 255), font=font)
        shown += 1

    return overlay, shown


def run_inference(image: Image.Image, run_localization: bool, detection_threshold: float):
    original, classifier_tensor, detector_tensor = prepare_uploaded_image(image)
    results = {}

    classifier = load_classifier()
    with torch.inference_mode():
        logits = classifier(classifier_tensor.unsqueeze(0)).squeeze(1)
        opacity_score = float(torch.sigmoid(logits.float()).item())

    label = (
        "Opacity-associated pattern"
        if opacity_score >= CLASSIFIER_THRESHOLD
        else "No-opacity-associated pattern"
    )

    results["classifier_label"] = label
    results["classifier_score"] = opacity_score
    results["classifier_threshold"] = CLASSIFIER_THRESHOLD

    overlay = None
    shown_count = 0
    total_proposals = 0
    top_score = None

    if run_localization:
        detector, _ = load_detector()
        with torch.inference_mode():
            output = detector([detector_tensor])[0]
        boxes = output["boxes"].detach().cpu().numpy()
        scores = output["scores"].detach().cpu().numpy()
        overlay, shown_count = draw_detections(
            original,
            {"boxes": boxes, "scores": scores},
            detection_threshold,
        )
        total_proposals = int(len(scores))
        top_score = float(scores.max()) if len(scores) else None

    return original, results, overlay, shown_count, total_proposals, top_score


